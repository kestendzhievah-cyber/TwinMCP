const DISPOSABLE_SET: ReadonlySet<string> = new Set(DISPOSABLE_EMAIL_DOMAINS);

/**
 * Whether `domain` (or any parent of it) is a listed throwaway domain:
 * "mailinator.com" and "inbox.mailinator.com" match, "notmailinator.org" or
 * a bare TLD never do.
 */
export function isDisposableDomain(domain: string): boolean {
  const d = domain.trim().toLowerCase().replace(/\.+$/, "");
  if (!d) return false;
  const labels = d.split(".");
  // Check the full domain, then each parent down to a two-label suffix.
  for (let i = 0; i <= labels.length - 2; i++) {
    if (DISPOSABLE_SET.has(labels.slice(i).join("."))) return true;
  }
  return false;
}

/** Whether an email address uses a throwaway domain (subdomains included). */
export function isDisposableEmail(email: string): boolean {
  const at = email.lastIndexOf("@");
  return at >= 0 && isDisposableDomain(email.slice(at + 1));
}
