"use client";

import { useState } from "react";
import { BrandLogo, MCP_LOGO_KEY, hasBrandLogo } from "@/components/brand/brand-logo";
import { Badge } from "@/components/ui/badge";
import { Card } from "@/components/ui/card";
import { Tabs, TabsContent, TabsList, TabsTrigger } from "@/components/ui/tabs";
import type { Locale } from "@/lib/i18n/locales";
import { IDE_LABELS, buildClientConfig, proxyUrl, type IdeKey } from "@/lib/mcp/client-config";
import { CodeSnippet } from "./code-snippet";

const SITE_URL = process.env.NEXT_PUBLIC_SITE_URL ?? "https://twinmcp.fr";

// The hero's product proof: the config block the dashboard's Connect panel
// generates, one tab per client it supports (IDE_LABELS order), built by the
// same generator (lib/mcp/client-config.ts) with placeholder server, MCP and
// key, so the example cannot drift from what users paste.
const IDES = Object.keys(IDE_LABELS) as IdeKey[];
const URL_EXAMPLE = proxyUrl(SITE_URL, "<server>", "<mcp>");
const CONFIGS = Object.fromEntries(
  IDES.map((ide) => [
    ide,
    buildClientConfig(ide, { url: URL_EXAMPLE, apiKey: "YOUR_API_KEY", label: "twinmcp" }),
  ])
) as Record<IdeKey, ReturnType<typeof buildClientConfig>>;

const COPY = {
  en: {
    title: (client: string) => `Your MCP, in ${client}`,
    live: "Live",
    tabs: "MCP client",
    other: "Other",
    otherClient: "any MCP client",
    foot: "Real config, generated by your dashboard.",
  },
  fr: {
    title: (client: string) => `Votre MCP dans ${client}`,
    live: "En ligne",
    tabs: "Client MCP",
    other: "Autre",
    otherClient: "tout client MCP",
    foot: "La vraie config, générée par votre tableau de bord.",
  },
} as const;

/** Tab label: VS Code is text only (no Microsoft mark); "other" is short. */
function tabLabel(ide: IdeKey, locale: Locale): string {
  if (ide === "vscode") return "VS Code";
  if (ide === "other") return COPY[locale].other;
  return IDE_LABELS[ide];
}

function logoKey(ide: IdeKey): string | null {
  if (ide === "other") return MCP_LOGO_KEY;
  return hasBrandLogo(ide) ? ide : null;
}

export function HeroConfigCard({ locale = "en" }: { locale?: Locale }) {
  const t = COPY[locale];
  const [ide, setIde] = useState<IdeKey>("cursor");
  const client = ide === "other" ? t.otherClient : tabLabel(ide, locale);

  return (
    <Card className="flex min-h-[340px] w-full min-w-0 flex-col gap-4 rounded-3xl p-5 shadow-lg sm:p-6">
      <div className="flex items-center justify-between gap-3">
        <p className="min-w-0 truncate font-display text-base font-semibold tracking-tight">
          {t.title(client)}
        </p>
        <Badge variant="success" className="shrink-0">
          <span aria-hidden className="h-1.5 w-1.5 rounded-full bg-success" />
          {t.live}
        </Badge>
      </div>

      <Tabs
        value={ide}
        onValueChange={(v) => setIde(v as IdeKey)}
        className="flex min-w-0 flex-1 flex-col"
      >
        <TabsList aria-label={t.tabs} className="h-auto w-full [scrollbar-width:thin]">
          {IDES.map((key) => {
            const logo = logoKey(key);
            return (
              <TabsTrigger key={key} value={key}>
                {logo && <BrandLogo slug={logo} size={16} decorative />}
                {tabLabel(key, locale)}
              </TabsTrigger>
            );
          })}
        </TabsList>
        {IDES.map((key) => (
          <TabsContent key={key} value={key} className="mt-3 min-w-0">
            <CodeSnippet
              code={CONFIGS[key].code}
              language={CONFIGS[key].language}
              locale={locale}
              codeClassName="h-64 overflow-auto whitespace-pre text-xs leading-relaxed"
            />
          </TabsContent>
        ))}
      </Tabs>

      <p className="text-xs text-muted-foreground">{t.foot}</p>
    </Card>
  );
}
